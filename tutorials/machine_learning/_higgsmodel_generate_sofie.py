"""Prepare the input of the SOFIE tutorials with RDataFrame (SOFIE_RDataFrame.C
and SOFIE_RDataFrame.py). It is not a tutorial itself, and it needs to be run
before them.

The script trains a simple deep neural network on the Higgs dataset with
PyTorch, exports the model to ONNX and generates the C++ code to evaluate it
with SOFIE. The batches of events to train the model are read from the dataset
with ROOT.Experimental.ML.RDataLoader.

SOFIE is not part of ROOT: it is a separate library, libSOFIE, that ROOT builds
together with it if RooFit or RDataFrame are enabled. It is loaded at runtime
with ctypes and used through its C interface, so ROOT doesn't need to know about
it when it is built, and the same code works in a Python script that doesn't use
ROOT. An external SOFIE library has to be in the library path. The generated
code only depends on the C++ standard library.

The trained model is saved as HiggsModel.onnx, and the code generated for it as
HiggsModel.hxx, which is used by the SOFIE tutorials with RDataFrame.
"""

import ctypes
import ctypes.util
import inspect
import os
import sys

import ROOT
import torch
import torch.nn as nn

# The input variables of the model, in the order of the input tensor
INPUT_VARIABLES = ["m_jj", "m_jjj", "m_lv", "m_jlv", "m_bb", "m_wbb", "m_wwbb"]


def PrepareData(batch_size=50):
    # get the input data
    inputFile = str(ROOT.gROOT.GetTutorialDir()) + "/machine_learning/data/Higgs_data.root"

    sig = ROOT.RDataFrame("sig_tree", inputFile)
    bkg = ROOT.RDataFrame("bkg_tree", inputFile)

    # The data loader reads the signal and the background together. The column
    # Type is the target, which is 1 for the signal and 0 for the background.
    # The dataset is small, so it is loaded in memory all at once: the events of
    # the two classes are then mixed in the batches by the shuffling.
    dataloader = ROOT.Experimental.ML.RDataLoader(
        [sig, bkg],
        batch_size=batch_size,
        columns=INPUT_VARIABLES + ["Type"],
        target="Type",
        shuffle=True,
        set_seed=1234,
        drop_remainder=True,
        load_eager=True,
    )

    # split data in training and test data
    return dataloader.train_test_split(test_size=0.5)


def CreateModel(nlayers=4, nunits=64):
    layers = []
    ninputs = len(INPUT_VARIABLES)
    for i in range(1, nlayers):
        layers += [nn.Linear(ninputs, nunits), nn.ReLU()]
        ninputs = nunits
    layers += [nn.Linear(ninputs, 1), nn.Sigmoid()]
    model = nn.Sequential(*layers)
    print(model)
    return model


def TrainModel(model, train_batches, epochs=5):
    criterion = nn.BCELoss()
    optimizer = torch.optim.Adam(model.parameters())
    for epoch in range(epochs):
        running_loss = 0.0
        nbatches = 0
        for x, y in train_batches.as_torch():
            optimizer.zero_grad()
            loss = criterion(model(x), y)
            loss.backward()
            optimizer.step()
            running_loss += loss.item()
            nbatches += 1
        print(f"Epoch {epoch + 1}/{epochs} - average loss: {running_loss / nbatches:.4f}")


def ExportModel(model, modelName):
    # need to evaluate the model before exporting to ONNX
    # and to provide a dummy input tensor to set the input model shape
    # (the batch size is fixed to 1 for the SOFIE inference)
    model.eval()

    modelFile = modelName + ".onnx"
    dummy_x = torch.randn(1, len(INPUT_VARIABLES))
    model(dummy_x)

    # check for torch.onnx.export parameters
    def filtered_kwargs(func, **candidate_kwargs):
        sig = inspect.signature(func)
        return {k: v for k, v in candidate_kwargs.items() if k in sig.parameters}

    kwargs = filtered_kwargs(
        torch.onnx.export,
        input_names=["input"],
        output_names=["output"],
        external_data=False,  # may not exist
        dynamo=True,  # may not exist
    )
    print("calling torch.onnx.export with parameters", kwargs)

    torch.onnx.export(model, dummy_x, modelFile, **kwargs)

    print("model exported to ONNX as", modelFile)
    return modelFile


def LoadSofie():
    # SOFIE is loaded with ctypes, the foreign function library of Python, so
    # that the code can also be generated by a Python script that doesn't use
    # ROOT. The library is looked for in the library path, and then next to the
    # ROOT libraries, where the SOFIE built together with ROOT is installed. An
    # external SOFIE library has to be in the library path.
    libraryNames = {"darwin": "libSOFIE.dylib", "win32": "SOFIE.dll"}
    libraryName = libraryNames.get(sys.platform, "libSOFIE.so")
    candidates = [ctypes.util.find_library("SOFIE"), libraryName]
    candidates.append(os.path.join(str(ROOT.gROOT.GetLibDir()), libraryName))
    for candidate in candidates:
        if not candidate:
            continue
        try:
            sofie = ctypes.CDLL(candidate)
            break
        except OSError:
            continue
    else:
        raise RuntimeError("The SOFIE library (" + libraryName + ") can't be loaded")

    # The functions of the C interface of SOFIE. The strings returned by SOFIE are
    # declared as void pointers, so that ctypes doesn't convert them to Python
    # strings: they have to be released with SOFIE_Free.
    sofie.SOFIE_GenerateCodeFromONNX.argtypes = [
        ctypes.c_char_p,  # onnx
        ctypes.c_size_t,  # size
        ctypes.c_char_p,  # modelName
        ctypes.c_uint,  # flags
        ctypes.POINTER(ctypes.c_void_p),  # code
        ctypes.POINTER(ctypes.c_void_p),  # error
    ]
    sofie.SOFIE_GenerateCodeFromONNX.restype = ctypes.c_size_t
    sofie.SOFIE_Free.argtypes = [ctypes.c_void_p]
    sofie.SOFIE_Free.restype = None
    return sofie


def GenerateCode(modelFile, modelName):
    sofie = LoadSofie()

    with open(modelFile, "rb") as f:
        onnx = f.read()

    code = ctypes.c_void_p()
    error = ctypes.c_void_p()
    # No flag is passed: the generated code only uses the C++ standard library
    # The length of the generated code is returned, or 0 if it can't be generated
    length = sofie.SOFIE_GenerateCodeFromONNX(
        onnx, len(onnx), modelName.encode(), 0, ctypes.byref(code), ctypes.byref(error)
    )
    try:
        if length == 0:
            message = ctypes.string_at(error).decode() if error.value else "unknown error"
            raise RuntimeError("SOFIE failed to generate the code: " + message)
        generatedCode = ctypes.string_at(code, length).decode()
    finally:
        sofie.SOFIE_Free(code)
        sofie.SOFIE_Free(error)

    # The code of the model is placed in the namespace SOFIE_<modelName>, and the
    # weights of the model are part of it
    modelHeaderFile = modelName + ".hxx"
    with open(modelHeaderFile, "w") as f:
        f.write(generatedCode)
    print("code generated with SOFIE in", modelHeaderFile)
    return modelHeaderFile


###################################################################
## Step 1 : Create and train the model, export it to ONNX
###################################################################

train_batches, test_batches = PrepareData()

# create dense model with 3 layers of 64 units and train it
model = CreateModel(3, 64)
TrainModel(model, train_batches)
modelName = "HiggsModel"
modelFile = ExportModel(model, modelName)

# evaluate the trained model on the first test events, for comparison with SOFIE
x_check, _ = next(iter(test_batches.as_torch()))
x_check = x_check[:10]
with torch.no_grad():
    ytorch = model(x_check).numpy()
x_check = x_check.numpy()

###################################################################
## Step 2 : Generate the inference code with SOFIE
###################################################################

modelHeaderFile = GenerateCode(modelFile, modelName)

###################################################################
## Step 3 : Compile the generated C++ model code
###################################################################

ROOT.gInterpreter.Declare('#include "' + modelHeaderFile + '"')

###################################################################
## Step 4: Evaluate the model
###################################################################

# get first the SOFIE session namespace
sofie = getattr(ROOT, "SOFIE_" + modelName)
session = sofie.Session()

for i in range(x_check.shape[0]):
    y = session.infer(x_check[i])
    print("input to model is ", x_check[i], "\n\t -> output using SOFIE = ", y[0], " using PyTorch = ", ytorch[i, 0])
    if abs(y[0] - ytorch[i, 0]) > 0.01:
        raise RuntimeError("ERROR: Result is different between SOFIE and PyTorch")

print("OK")
