  void AppendUTF8(std::string& Out, char32_t C) {
    if (!IsValidCodePoint(C)) {
      C = kInvalidChar;
    }
    if (C < 0x80) {
      Out += static_cast<char>(C);
    } else if (C < 0x800) {
      Out += static_cast<char>(0xC0 | (C >> 6));
      Out += static_cast<char>(0x80 | (C & 0x3F));
    } else if (C < 0x10000) {
      Out += static_cast<char>(0xE0 | (C >> 12));
      Out += static_cast<char>(0x80 | ((C >> 6) & 0x3F));
      Out += static_cast<char>(0x80 | (C & 0x3F));
    } else {
      Out += static_cast<char>(0xF0 | (C >> 18));
      Out += static_cast<char>(0x80 | ((C >> 12) & 0x3F));
      Out += static_cast<char>(0x80 | ((C >> 6) & 0x3F));
      Out += static_cast<char>(0x80 | (C & 0x3F));
    }
  }

  std::u32string UTF8ToUTF32(const char* S, size_t Len) {
    std::u32string Ret;
    Ret.reserve(Len);
    size_t I = 0;
    while (I < Len) {
      const unsigned char Lead = static_cast<unsigned char>(S[I]);
      const size_t SeqLen = UTF8SequenceLength(Lead);
      if (SeqLen == 0 || I + SeqLen > Len) {
        // Not a lead byte, or the string ends mid-sequence.
        Ret += kInvalidChar;
        ++I;
        continue;
      }
      if (SeqLen == 1) {
        Ret += static_cast<char32_t>(Lead);
        ++I;
        continue;
      }
      static const unsigned char LeadMask[5] = {0, 0, 0x1F, 0x0F, 0x07};
      char32_t Value = Lead & LeadMask[SeqLen];
      size_t NumCont = 0;
      for (; NumCont < SeqLen - 1; ++NumCont) {
        const unsigned char Cont = static_cast<unsigned char>(S[I + 1 + NumCont]);
        if (!IsUTF8Continuation(Cont)) break;
        Value = (Value << 6) | (Cont & 0x3F);
      }
      if (NumCont != SeqLen - 1 || !IsValidCodePoint(Value)) {
        // Truncated or surrogate/out-of-range: consume only what we validated
        // so that a following lead byte still starts a fresh character.
        Ret += kInvalidChar;
        I += 1 + NumCont;
        continue;
      }
      Ret += Value;
      I += SeqLen;
    }
    return Ret;
  }

  std::string UTF32ToUTF8(const char32_t* S, size_t Len) {
    std::string Ret;
    Ret.reserve(Len);
    for (size_t I = 0; I < Len; ++I) {
      AppendUTF8(Ret, S[I]);
    }
    return Ret;
  }

  size_t CharWidth(char32_t C) {
    if (C < 0x7F) {
      // Fast path for ASCII. Control characters never reach the line buffer -
      // the editor rejects them - but the prompt may contain a stray one, and
      // claiming a column for it keeps the cursor arithmetic honest.
      return C < 0x20 ? 0 : 1;
    }
    if (C < 0xA0) return 0;      // C1 controls
    if (InRanges(kZeroWidth, C)) return 0;
    if (InRanges(kDoubleWidth, C)) return 2;
    return 1;
  }

  UTF8Decoder::EResult
  UTF8Decoder::Push(unsigned char C, char32_t& Out, bool& Reprocess) {
    Reprocess = false;
    if (fPending == 0) {
      const size_t SeqLen = UTF8SequenceLength(C);
      if (SeqLen == 0) {
        // A continuation byte with nothing to continue, or a byte that is
        // never valid UTF-8.
        Out = kInvalidChar;
        return kInvalid;
      }
      if (SeqLen == 1) {
        Out = C;
        return kComplete;
      }
      static const unsigned char LeadMask[5] = {0, 0, 0x1F, 0x0F, 0x07};
      fValue = C & LeadMask[SeqLen];
      fLength = SeqLen;
      fPending = SeqLen - 1;
      return kNeedMore;
    }

    if (!IsUTF8Continuation(C)) {
      // The sequence was cut short. Report it and let the caller re-feed this
      // byte, which may well be the start of the next character (or an ESC
      // that we must not swallow).
      Reset();
      Out = kInvalidChar;
      Reprocess = true;
      return kInvalid;
    }

    fValue = (fValue << 6) | (C & 0x3F);
    if (--fPending != 0) {
      return kNeedMore;
    }

    const char32_t Value = fValue;
    const size_t Length = fLength;
    Reset();
    // Reject surrogates, out-of-range values and overlong encodings.
    static const char32_t MinForLength[5] = {0, 0, 0x80, 0x800, 0x10000};
    if (!IsValidCodePoint(Value) || Value < MinForLength[Length]) {
      Out = kInvalidChar;
      return kInvalid;
    }
    Out = Value;
    return kComplete;
  }
