  template <size_t N>
  bool InRanges(const Range (&Ranges)[N], char32_t C) {
    size_t Lo = 0;
    size_t Hi = N;
    while (Lo < Hi) {
      size_t Mid = Lo + (Hi - Lo) / 2;
      if (C < Ranges[Mid].fFirst) {
        Hi = Mid;
      } else if (C > Ranges[Mid].fLast) {
        Lo = Mid + 1;
      } else {
        return true;
      }
    }
    return false;
  }
